create table if not exists public.perfiles_oficial (
    usuario_id uuid primary key references auth.users (id) on delete cascade,
    nombre text not null,
    activo boolean not null default true,
    created_at timestamptz not null default now()
);

alter table public.perfiles_oficial enable row level security;
grant select on public.perfiles_oficial to authenticated;

drop policy if exists "oficial lee su perfil activo" on public.perfiles_oficial;
create policy "oficial lee su perfil activo"
    on public.perfiles_oficial for select to authenticated
    using (usuario_id = (select auth.uid()) and activo);

create table if not exists public.reportes_estado (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    vehiculo_id bigint references public.vehiculos (id),
    patente text not null,
    rut_conductor text,
    estado text not null check (
        estado in ('Operativo', 'Alerta', 'Requiere Mantención', 'Crítico')
    ),
    descripcion text not null default '',
    evidencia_path text,
    registrado_por uuid references auth.users (id)
);

alter table public.reportes_estado enable row level security;
grant select on public.reportes_estado to authenticated;

drop policy if exists "oficial lee reportes" on public.reportes_estado;
create policy "oficial lee reportes"
    on public.reportes_estado for select to authenticated
    using (
        exists (
            select 1 from public.perfiles_oficial po
            where po.usuario_id = (select auth.uid()) and po.activo
        )
    );

insert into storage.buckets (id, name, public)
values ('evidencias-vehiculares', 'evidencias-vehiculares', false)
on conflict (id) do update set public = false;

drop policy if exists "oficial consulta evidencias vehiculares" on storage.objects;
create policy "oficial consulta evidencias vehiculares"
    on storage.objects for select to authenticated
    using (
        bucket_id = 'evidencias-vehiculares'
        and exists (
            select 1 from public.perfiles_oficial po
            where po.usuario_id = (select auth.uid()) and po.activo
        )
    );

