create or replace function public.registrar_control_acceso(
    p_patente text,
    p_rut text,
    p_puesto text,
    p_evidencia_path text
)
returns table (
    bitacora_id bigint,
    decision text,
    detalle text,
    patente text,
    rut_conductor text,
    nombre_conductor text,
    estado_vehiculo text,
    autorizacion_vigente boolean,
    ingreso_permitido boolean
)
language plpgsql
security definer
set search_path = pg_catalog, public, auth
as $$
declare
    v_guardia_id uuid := auth.uid();
    v_vehiculo_id bigint;
    v_conductor_id bigint;
    v_autorizacion_id bigint;
    v_patente text;
    v_rut text;
    v_nombre text;
    v_estado_vehiculo text;
    v_estado_conductor text;
    v_autorizacion_vigente boolean := false;
    v_decision text;
    v_detalle text;
    v_ingreso_permitido boolean := false;
    v_bitacora_id bigint;
begin
    if v_guardia_id is null or not exists (
        select 1 from public.perfiles_guardia pg
        where pg.usuario_id = v_guardia_id and pg.activo
    ) then
        raise exception 'Se requiere una cuenta de Guardia activa.';
    end if;

    if nullif(trim(p_patente), '') is null
        or nullif(trim(p_rut), '') is null
        or nullif(trim(p_puesto), '') is null
        or nullif(trim(p_evidencia_path), '') is null then
        raise exception 'Patente, RUT, puesto y evidencia son obligatorios.';
    end if;

    if split_part(trim(p_evidencia_path), '/', 1) <> v_guardia_id::text
        or not exists (
            select 1 from storage.objects o
            where o.bucket_id = 'evidencias-vehiculares'
                and o.name = trim(p_evidencia_path)
        ) then
        raise exception 'La evidencia debe existir y pertenecer al Guardia autenticado.';
    end if;

    select v.id, v.patente, v.estado_operativo
    into v_vehiculo_id, v_patente, v_estado_vehiculo
    from public.vehiculos v
    where regexp_replace(upper(v.patente), '[^A-Z0-9]', '', 'g')
        = regexp_replace(upper(p_patente), '[^A-Z0-9]', '', 'g')
    limit 1;

    select c.id, c.rut, c.nombre_completo, c.estado
    into v_conductor_id, v_rut, v_nombre, v_estado_conductor
    from public.conductores c
    where regexp_replace(upper(c.rut), '[^0-9K]', '', 'g')
        = regexp_replace(upper(p_rut), '[^0-9K]', '', 'g')
    limit 1;

    if v_vehiculo_id is not null and v_conductor_id is not null then
        select a.id
        into v_autorizacion_id
        from public.autorizaciones a
        where regexp_replace(upper(a.patente), '[^A-Z0-9]', '', 'g')
                = regexp_replace(upper(v_patente), '[^A-Z0-9]', '', 'g')
            and regexp_replace(upper(a.rut_conductor), '[^0-9K]', '', 'g')
                = regexp_replace(upper(v_rut), '[^0-9K]', '', 'g')
            and a.vigente is true
            and a.fecha_asignacion <= now()
            and (a.fecha_vencimiento is null or a.fecha_vencimiento >= now())
        order by a.fecha_asignacion desc
        limit 1;
        v_autorizacion_vigente := v_autorizacion_id is not null;
    end if;

    if v_vehiculo_id is null then
        v_decision := 'Denegado';
        v_detalle := 'La patente no existe en el catalogo de vehiculos.';
    elsif v_conductor_id is null then
        v_decision := 'Denegado';
        v_detalle := 'El RUT no existe en el registro de conductores.';
    elsif lower(coalesce(v_estado_conductor, '')) <> 'activo' then
        v_decision := 'Denegado';
        v_detalle := 'El conductor no se encuentra habilitado.';
    elsif not v_autorizacion_vigente then
        v_decision := 'Denegado';
        v_detalle := 'No existe autorizacion vigente para este conductor y vehiculo.';
    elsif lower(coalesce(v_estado_vehiculo, '')) <> 'operativo' then
        v_decision := 'Alerta de Estado';
        v_detalle := 'El vehiculo requiere revision; ingreso bloqueado.';
    else
        v_decision := 'Autorizado';
        v_detalle := 'Conductor habilitado, autorizacion vigente y vehiculo operativo.';
        v_ingreso_permitido := true;
    end if;

    insert into public.bitacora_accesos (
        guardia_id, patente_ingresada, rut_ingresado, vehiculo_id,
        conductor_id, autorizacion_id, puesto, decision, detalle, evidencia_path
    ) values (
        v_guardia_id, upper(trim(p_patente)), upper(trim(p_rut)), v_vehiculo_id,
        v_conductor_id, v_autorizacion_id, trim(p_puesto), v_decision, v_detalle,
        trim(p_evidencia_path)
    ) returning id into v_bitacora_id;

    return query select
        v_bitacora_id, v_decision, v_detalle, v_patente, v_rut, v_nombre,
        v_estado_vehiculo, v_autorizacion_vigente, v_ingreso_permitido;
end;
$$;

revoke all on function public.registrar_control_acceso(text, text, text, text)
    from public, anon;
grant execute on function public.registrar_control_acceso(text, text, text, text)
    to authenticated;