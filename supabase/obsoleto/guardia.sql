alter table public.autorizaciones
    add column if not exists fecha_vencimiento timestamptz;

create table if not exists public.perfiles_guardia (
    usuario_id uuid primary key references auth.users (id) on delete cascade,
    nombre text not null,
    activo boolean not null default true,
    created_at timestamptz not null default now()
);

create table if not exists public.bitacora_accesos (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    guardia_id uuid not null references auth.users (id),
    patente_ingresada text not null,
    rut_ingresado text not null,
    vehiculo_id bigint,
    conductor_id bigint,
    autorizacion_id bigint,
    puesto text not null,
    decision text not null check (
        decision in ('Autorizado', 'Denegado', 'Alerta de Estado')
    ),
    detalle text not null,
    evidencia_path text not null
);

create index if not exists bitacora_accesos_created_at_idx
    on public.bitacora_accesos (created_at desc);
create index if not exists bitacora_accesos_guardia_id_idx
    on public.bitacora_accesos (guardia_id, created_at desc);

alter table public.perfiles_guardia enable row level security;
alter table public.bitacora_accesos enable row level security;
grant select on public.perfiles_guardia, public.bitacora_accesos to authenticated;

drop policy if exists "guardia lee su perfil activo" on public.perfiles_guardia;
create policy "guardia lee su perfil activo"
    on public.perfiles_guardia for select to authenticated
    using (usuario_id = (select auth.uid()) and activo);

drop policy if exists "guardia lee sus controles" on public.bitacora_accesos;
create policy "guardia lee sus controles"
    on public.bitacora_accesos for select to authenticated
    using (guardia_id = (select auth.uid()));

